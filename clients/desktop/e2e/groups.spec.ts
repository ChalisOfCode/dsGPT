import {test, expect} from "@playwright/test";

test("owner reviews real source associations, corrects and removes links without changing originals", async ({page, request}) => {
  const base = "http://127.0.0.1:8766";
  const {token} = await (await request.get(base + "/test-credential")).json();
  const headers = {Authorization: `Bearer ${token}`};
  const ids: string[] = [];
  for (const title of ["Orchard source one", "Orchard source two"]) {
    const r = await request.post(base + "/v1/work/tasks", {headers, data: {title, requirements: "Review https://github.com/Acme/Orchard only", build_target: "files"}});
    expect(r.ok()).toBeTruthy(); ids.push((await r.json()).id);
  }
  await page.goto("/");
  await page.getByLabel("Backend address").fill(base);
  await page.getByLabel("Owner credential").fill(token);
  await page.getByRole("button", {name:"Connect to dsGPT"}).click();
  await page.getByRole("button", {name:"Settings", exact:true}).click();
  await page.getByRole("button", {name:"History and retrieval →"}).click();
  const panel = page.getByRole("region", {name:"Related projects"});
  await panel.getByRole("button", {name:"Browse project groups"}).click();
  await panel.getByLabel("Sources to review").selectOption("task");
  await panel.getByRole("button", {name:"Load source page"}).click();
  await panel.getByRole("checkbox", {name:/Orchard source one/}).check();
  await panel.getByRole("checkbox", {name:/Orchard source two/}).check();
  await panel.getByRole("button", {name:"Review associations"}).click();
  await expect(panel.getByText("exact identifier: acme/orchard (2 sources)")).toBeVisible();
  expect(await (await request.get(base + "/v1/project-groups", {headers})).json()).toEqual([]);
  await panel.getByLabel("Group name", {exact:true}).fill("Orchard review");
  await panel.getByRole("button", {name:"Link reviewed sources"}).click();
  await expect(panel.getByRole("status")).toContainText("accepted");
  const groups = await (await request.get(base + "/v1/project-groups", {headers})).json();
  const id = groups[0].id;
  await panel.getByLabel("Project group", {exact:true}).selectOption(id);
  await panel.getByRole("button", {name:"Read linked sources"}).click();
  await expect(panel.getByRole("list", {name:"Linked originals"}).getByRole("listitem")).toHaveCount(2);
  await panel.getByLabel("Group name", {exact:true}).fill("Corrected orchard");
  await panel.getByRole("button", {name:"Rename group"}).click();
  await expect(panel.getByRole("status")).toContainText("renamed");
  await panel.getByLabel("Project group", {exact:true}).selectOption(id);
  await panel.getByRole("checkbox", {name:/Orchard source one/}).check();
  await panel.getByRole("button", {name:"Review associations"}).click();
  await panel.getByRole("button", {name:"Reject links to this group"}).click();
  await expect(panel.getByRole("status")).toContainText("rejected");
  expect((await (await request.get(base + `/v1/project-groups/${id}`, {headers})).json()).members).toHaveLength(1);
  await panel.getByLabel("Project group", {exact:true}).selectOption(id);
  await panel.getByRole("checkbox", {name:/Orchard source two/}).check();
  await panel.getByRole("button", {name:"Review associations"}).click();
  await panel.getByRole("button", {name:"Leave ungrouped"}).click();
  await expect(panel.getByRole("status")).toContainText("ungrouped");
  expect((await (await request.get(base + `/v1/project-groups/${id}`, {headers})).json()).members).toHaveLength(0);
  await panel.getByLabel("Project group", {exact:true}).selectOption(id);
  await panel.getByRole("button", {name:"Remove group…"}).click();
  await panel.getByRole("button", {name:"Confirm group removal"}).click();
  await expect(panel.getByRole("status")).toContainText("originals retained");
  for (const source of ids) expect((await (await request.get(base + `/v1/work/tasks/${source}`, {headers})).json()).requirements).toBe("Review https://github.com/Acme/Orchard only");
});
